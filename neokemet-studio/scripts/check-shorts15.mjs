#!/usr/bin/env node
/** Local-only quality gate. Never writes to existing projects or contacts AI. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const slug=process.argv[2]||"royal-cache-15s-v2";
if(!/^[a-z0-9][a-z0-9-]{0,59}$/.test(slug)) {console.error("Invalid project slug");process.exit(1)}
const f=path.join(ROOT,"projects",slug,"project.json");
if(!fs.existsSync(f)){console.error("Project missing: "+f);process.exit(1)}
const p=JSON.parse(fs.readFileSync(f,"utf8"));
const errors=[], warnings=[];
const durations=[3,5,4,3], shortsTemplates=["shorts15-hook","shorts15-danger","shorts15-reveal","shorts15-cta"];
const shots=[2,3,3,2];
if(p.format!=="9:16")errors.push("Format must be 9:16");
if(p.fps!==30)errors.push("FPS must be 30 for the 450-frame master");
if(!p.subtitles)errors.push("Bold captions must be enabled");
if(!Array.isArray(p.scenes)||p.scenes.length!==4)errors.push("Requires four scenes");
let sum=0,estimatedWords=0;const ids=new Set();
for(let i=0;i<(p.scenes||[]).length;i++){
 const s=p.scenes[i];sum+=(s.durationSec||0);
 if(s.template!==shortsTemplates[i])errors.push(`Scene ${i+1} must use ${shortsTemplates[i]}`);
 if(s.durationSec!==durations[i])errors.push(`Scene ${i+1} must be ${durations[i]}s`);
 if(ids.has(s.id))errors.push(`Duplicate scene ID ${s.id}`);
 ids.add(s.id);
 const w=(s.narration||"").trim().split(/\s+/).filter(Boolean).length;estimatedWords+=w;
 if(w===0)warnings.push(`Scene ${i+1} has no narration`);
 // Until recorded audio is present, use the studio's conservative 135 WPM estimator.
 const estimated=w/135*60;
 if(0.5+estimated+0.1>durations[i])warnings.push(`Scene ${i+1} estimated VO may not fit ${durations[i]}s; record and validate before publishing.`);
 if(s.narrationFile && !fs.existsSync(path.resolve(path.dirname(f),s.narrationFile))) errors.push(`Scene ${i+1} references a missing narration file`);
}
if(sum!==15)errors.push(`Total duration ${sum}s; expected 15s`);
if(p.scenes?.[0]?.durationSec>3)errors.push("Hook must start in first 3s");
if(shots.reduce((a,b)=>a+b,0)!==10)errors.push("Incorrect 10-shot preset");
console.log(`NeoKemetAI Shorts15 QA: ${slug}\n4 scenes / ${shots.join('+')} = 10 visual shots / ${sum}s @30fps / 450 frames`);
console.log(`Voiceover: ${estimatedWords} words; audio not generated by this checker`);
console.log(`Potential issues: ${warnings.length} warning(s), ${errors.length} error(s)`);
for(const w of warnings)console.log("WARNING: "+w);
for(const e of errors)console.error("ERROR: "+e);
if(errors.length)process.exit(1);
console.log("PASS — storyboard structure, pacing, graphics preset and captions configuration.");
